"""Set up the MACE Monte Carlo sweep for Li4Ti5O12: one folder per run.

Edit the settings block below, then run::

    python demos/li4ti5o12_short_range_order/setup_sweep.py

For every (temperature, start, seed) this creates
``SWEEP_DIR/T<T>K_<start>_seed<seed>/run_mc.py``, a small script holding that
run's settings. Run it with ``python run_mc.py`` (from any directory), locally
or as a cluster job; running it again resumes the run. All of the run's
outputs go into its folder. See "MACE Monte Carlo" in this demo's README.

Folders that already have a ``run_mc.py`` are left alone, so you can add
temperatures or seeds and rerun this script. To regenerate one run's script,
delete it and rerun.
"""

from __future__ import annotations

import json
from pathlib import Path

import common

HERE = Path(__file__).resolve().parent

# --- Sweep settings: edit these ----------------------------------------------
MODEL = "/path/to/mace.model"  # MACE model file, as a path on the machine that runs the jobs
TEMPERATURES = [600, 900, 1200, 1500, 2000, 3000]  # K
STARTS = ["ordered", "random"]  # both: converging to the same alpha is the equilibration check
SEEDS = [0]  # more seeds = more independent chains per temperature
RELAX = True  # relax each arrangement (positions + cell); False = single-point energies, much faster
RELAX_CELL = True  # with RELAX, relax the cell as well as the positions
FMAX = 0.02  # relaxation force threshold, eV/A
MAX_RELAX_STEPS = 1000  # optimizer step cap per relaxation
STEPS = 100_000  # total Monte Carlo steps per run; jobs usually stop at wall time and resume
THREADS = None  # torch threads; None uses SLURM_CPUS_PER_TASK if set, else all cores
DEVICE = "cpu"  # "cpu" or "cuda"
LOG_EVERY = 20  # steps between progress lines
SWEEP_DIR = HERE / "sweep"  # where the run folders go
# ------------------------------------------------------------------------------

RUN_SCRIPT = '''"""MACE Monte Carlo for Li4Ti5O12 short-range order: {name}.

Run with ``python run_mc.py`` from any directory; running it again resumes
where it stopped. Outputs go into this folder. Generated by setup_sweep.py;
don't change SETTINGS once the run has started (the run refuses to mix
settings) -- make a new folder instead.
"""

from pathlib import Path
import sys

sys.path[:0] = [{src}, {demo}]
from mace_mc import run_temperature  # noqa: E402

SETTINGS = {{
    "temperature_K": {temperature_K},  # K
    "initial": {initial},  # starting arrangement: "ordered" (lowest-energy Ewald, alpha_1 = -0.2) or "random"
    "seed": {seed},  # seeds the Monte Carlo moves and the random start
    "model": {model},  # MACE model file
    "device": {device},  # torch device
    "relax": {relax},  # relax each arrangement before reading its energy
    "relax_cell": {relax_cell},  # with relax, relax the cell too
    "fmax": {fmax},  # relaxation force threshold, eV/A
    "max_relax_steps": {max_relax_steps},  # optimizer step cap per relaxation
    "steps": {steps},  # total Monte Carlo steps, including those already done
    "threads": {threads},  # None: SLURM_CPUS_PER_TASK if set, else all cores
    "log_every": {log_every},  # steps between progress lines
}}

if __name__ == "__main__":
    run_temperature(Path(__file__).resolve().parent, **SETTINGS)
'''


def literal(value) -> str:
    """Python source for ``value``, with double-quoted strings."""
    return json.dumps(value) if isinstance(value, str) else repr(value)


def main() -> None:
    model = Path(MODEL).expanduser()
    if MODEL == "/path/to/mace.model":
        raise SystemExit(f"Edit the settings block at the top of {Path(__file__).name} first (MODEL is still the placeholder).")
    if not model.is_file():
        raise SystemExit(f"MODEL file not found: {model}")
    if not (TEMPERATURES and STARTS and SEEDS):
        raise SystemExit("TEMPERATURES, STARTS and SEEDS must each list at least one value.")
    if any(t <= 0 for t in TEMPERATURES):
        raise SystemExit(f"TEMPERATURES must all be positive, got {TEMPERATURES}.")
    if bad := [s for s in STARTS if s not in ("ordered", "random")]:
        raise SystemExit(f"STARTS may only contain 'ordered' and 'random', got {bad}.")
    if "ordered" in STARTS and not (common.RESULTS / "sro_summary.json").exists():
        raise SystemExit("The ordered start comes from results/sro_summary.json; run run.py first.")

    sweep_dir = Path(SWEEP_DIR).expanduser().resolve()
    created, existing = [], []
    for initial in STARTS:
        for seed in SEEDS:
            for temperature in TEMPERATURES:
                name = common.run_name(temperature, initial, seed)
                script = sweep_dir / name / "run_mc.py"
                if script.exists():
                    existing.append(name)
                    continue
                script.parent.mkdir(parents=True, exist_ok=True)
                script.write_text(
                    RUN_SCRIPT.format(
                        name=name,
                        **{
                            key: literal(value)
                            for key, value in {
                                "src": str(HERE.parent.parent / "src"),
                                "demo": str(HERE),
                                "temperature_K": float(temperature),
                                "initial": initial,
                                "seed": seed,
                                "model": str(model.resolve()),
                                "device": DEVICE,
                                "relax": RELAX,
                                "relax_cell": RELAX_CELL,
                                "fmax": FMAX,
                                "max_relax_steps": MAX_RELAX_STEPS,
                                "steps": STEPS,
                                "threads": THREADS,
                                "log_every": LOG_EVERY,
                            }.items()
                        },
                    )
                )
                created.append(name)

    print(f"Sweep folder: {sweep_dir}")
    print(f"Created {len(created)} run(s): {', '.join(created) or '-'}")
    if existing:
        print(f"Left {len(existing)} existing run(s) unchanged: {', '.join(existing)}")
    print("\nRun one (rerun to resume):")
    print(f"    python {sweep_dir / (created or existing)[0] / 'run_mc.py'}")
    print('To run them as cluster jobs, see "Running on a cluster" in demos/mgal2o4_inversion/README.md.')


if __name__ == "__main__":
    main()
